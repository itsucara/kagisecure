//! Agent test logins: logins kagisecure generates for an agent's test users, whose password the
//! agent never receives ([ADR-0048](../../../../docs/decisions/0048-agent-test-logins.md)).
//!
//! # Where this sits
//!
//! `create_test_login`, `list_test_logins` and `trash_test_logins` are served by [`crate::service`], which reads the
//! policy out of the test-login vault (`VaultMeta.purpose`, ADR-0048 §1) and writes the item in
//! one vault transaction. This module holds what that needs beyond the vault:
//!
//! * [`TestLoginBroker`] — process-wide, like the agent-fill broker: the per-agent create limit
//!   of §11, which must survive a reconnect and a vault lock, and the passive notices of §10 the
//!   app drains;
//! * [`origin_auto`] — §3's rule for where no sheet is needed;
//! * [`TestLoginPass`] — the one way a sealed item at an allowed origin reaches an agent fill's
//!   release without a person's grant (§7). Only [`TestLoginPass::for_fill`] makes one, and it
//!   checks the switch, the vault, the seal and the origin itself.
//!
//! Nothing here reads a secret: the password is generated by `kagisecure_core::generator` into a
//! `Secret` inside the service's transaction, sealed by `kagisecure_core`, and never opened on
//! this side. `crossing`'s scan test holds this module to that.

